type Key = keyof typeof EN;
const forced = new URLSearchParams(location.search).get('lang');
export let lang: 'en' | 'es' = forced === 'es' || forced === 'en' ? forced : (navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en';
export function setLang(l: 'en' | 'es') {
  lang = l;
  document.documentElement.lang = l;
}
export function t(k: Key | string, vars: Record<string, string | number> = {}): string {
  const dict = lang === 'es' ? ES : EN;
  let s = (dict as Record<string, string>)[k] ?? (EN as Record<string, string>)[k] ?? k;
  for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b));
  return s;
}
